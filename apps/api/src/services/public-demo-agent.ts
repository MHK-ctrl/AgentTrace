import { AgentTrace } from "agenttrace-sdk";

const wait = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

export interface PublicDemoAgentOptions {
  apiKey: string;
  endpoint: string;
}

/**
 * A deterministic, side-effect-free support agent. Every model call, tool and
 * database operation is instrumented by the real AgentTrace SDK and sent
 * through authenticated ingestion into the visitor's isolated demo project.
 */
export async function runPublicDemoAgent(
  options: PublicDemoAgentOptions,
): Promise<{ traceId: string }> {
  const tracing = new AgentTrace({
    apiKey: options.apiKey,
    endpoint: options.endpoint,
    captureInputOutput: true,
    captureMaxBytes: 4 * 1024,
    flushIntervalMs: 60_000,
    maxBatchSize: 200,
    maxQueueSize: 1_000,
    requestTimeoutMs: 8_000,
    retries: 2,
    failOpen: false,
    tags: ["public-demo", "synthetic"],
  });

  let traceId = "";

  try {
    await tracing.trace(
      {
        name: "Refund request · order 4821",
        agentName: "support-copilot",
        isDemo: true,
        captureInputOutput: true,
        metadata: {
          environment: "public-demo",
          synthetic: true,
          channel: "email",
          scenario: "retry_success",
          notice: "Generated by the AgentTrace public demo. Synthetic data only.",
        },
        tags: ["demo", "public-demo", "retry-success"],
      },
      async (trace) => {
        traceId = trace.id;

        await trace.llm(
          {
            name: "plan-resolution",
            model: "demo-reasoner",
            provider: "agenttrace-sim",
            tokenUsage: { input: 812, output: 164 },
            input: {
              message: "I was charged twice for order 4821. Can I get a refund?",
            },
            attributes: { "gen_ai.operation.name": "chat" },
          },
          async (span) => {
            await wait(120);
            span.event("intent.classified", { confidence: 0.94 });
            return {
              intent: "billing_refund",
              confidence: 0.94,
              nextAction: "lookup_customer",
            };
          },
        );

        await trace.tool(
          {
            name: "browser.search",
            input: { query: "enterprise refund policy duplicate charge" },
            attributes: { "search.backend": "simulated-index" },
          },
          async (span) => {
            await wait(90);
            const response = await trace.api(
              {
                name: "search-api.request",
                attributes: { "http.method": "GET", "http.status_code": 200 },
              },
              async () => {
                await wait(110);
                return { statusCode: 200 };
              },
            );
            span.event("search.completed", { results: 3, status: response.statusCode });
            return { resultCount: 3, topSource: "docs.example.com" };
          },
        );

        const retentionPolicy = {
          customerId: "CUST-1042",
          plan: "enterprise",
          duplicateCharge: true,
          eligibleForRefund: true,
        };

        try {
          await trace.database(
            {
              name: "crm.customer-lookup",
              attemptNumber: 1,
              input: {
                query: "SELECT * FROM customers WHERE order_id = $1",
                orderId: "4821",
              },
              attributes: { "db.system": "postgresql", "retry.eligible": true },
            },
            async () => {
              await wait(80);
              const failure = new Error("Synthetic CRM connection reset");
              failure.name = "CRMConnectionError";
              failure.stack =
                "CRMConnectionError: Synthetic CRM connection reset\n    at crm.ts:44:9";
              throw failure;
            },
          );
        } catch {
          // The failed span is recorded, then the agent retries below.
        }

        await trace.database(
          {
            name: "retry · crm.customer-lookup",
            attemptNumber: 2,
            input: { customerId: "CUST-1042", retryOf: "crm.customer-lookup" },
            attributes: { "retry.attempt": 2, "db.system": "postgresql" },
          },
          async (span) => {
            await wait(90);
            span.event("retry.succeeded", { attempt: 2 });
            return retentionPolicy;
          },
        );

        return trace.llm(
          {
            name: "draft-reply",
            model: "demo-reasoner",
            provider: "agenttrace-sim",
            tokenUsage: { input: 1_442, output: 246 },
            input: {
              customerId: "CUST-1042",
              policy: "duplicate-charge-refund",
            },
            attributes: { "gen_ai.operation.name": "chat" },
          },
          async () => {
            await wait(110);
            return {
              text: "The duplicate charge is confirmed. A refund has been queued to the original payment method.",
              confidence: 0.97,
              refundQueued: true,
            };
          },
        );
      },
    );

    await tracing.shutdown();
    if (!traceId) throw new Error("The sample agent did not create a trace");
    return { traceId };
  } finally {
    await tracing.shutdown().catch(() => undefined);
  }
}
